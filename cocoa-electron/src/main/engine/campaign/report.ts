// A campaign's own report over its members' results (convention §8.3).

import fs from 'node:fs'
import path from 'node:path'
import {
  attachment_arg,
  attachment_count,
  attachment_dir,
  prepare_attachments,
  settle_attachments
} from '../attachments'
import type { Engine } from '../engine'
import { EngineError } from '../errors'
import * as invoke from '../invoke'
import type { Invocation } from '../invoke'
import { all_params, now_stamp } from '../record'
import type { CampaignMembersFile, CampaignRecord, RunRecord } from '../record'
import { primary_report_path, report_dir, report_on_disk } from '../report_paths'
import { locked_refusal } from '../report_lock'
import { write_atomic } from '../store'
import type { Campaign } from './campaign'

/** Why a campaign run has no report of its own: every member must have succeeded (§8.3). */
function blockers_of(engine: Engine, record: CampaignRecord): string[] {
  const reasons: string[] = []
  if (record.launch_failures.length > 0) {
    reasons.push(`${record.launch_failures.length} launch(es) failed`)
  }
  for (const member of engine.resolve_members(record)) {
    if (member.record === null) {
      reasons.push(`member \`${member.job_name}\` run ${member.run_id} cannot be resolved`)
    } else if (member.record.status !== 'SUCCEEDED') {
      reasons.push(
        `member \`${member.job_name}\` run ${member.run_id} ended ${member.record.status}`
      )
    }
  }
  return reasons
}

/**
 * Whether the campaign run's report can be regenerated by hand now: it has
 * had one — landed or failed — and is not already due again.
 */
export function campaign_report_rerunnable(engine: Engine, record: CampaignRecord): boolean {
  return record.report?.attempted === true && blockers_of(engine, record).length === 0
}

/**
 * Asks for a campaign run's report again, by hand (§8.3), as a job run's is
 * asked for (§7.3.2): nothing runs here. The report is marked due, the run
 * reads `ANALYZING`, and the refresh tick runs it. `at` is kept: it is the
 * campaign's end, which a regenerate does not move.
 */
export function request_campaign_report(engine: Engine, campaign: Campaign, run_id: number): void {
  campaign.usable_manifest()
  const record = campaign.runs.record(run_id)
  const blockers = blockers_of(engine, record)
  if (blockers.length > 0) {
    throw EngineError.validation(`no campaign report: ${blockers.join(', ')}`)
  }
  if (record.report === undefined || !record.report.attempted) {
    throw EngineError.validation(`the report of campaign run ${run_id} is already running`)
  }
  if (record.report_locked === true) {
    throw locked_refusal(`campaign run ${run_id}`, 'regenerate it')
  }
  const at = record.report.at
  record.report = { attempted: false, ...(at !== undefined ? { at } : {}) }
  campaign.runs.write(record)
}

/** Runs the campaign's report over its members' results (§8.3). */
export async function campaign_report(
  engine: Engine,
  campaign: Campaign,
  run_id: number
): Promise<void> {
  const manifest = campaign.usable_manifest()
  const record = campaign.runs.record(run_id)

  const blockers = blockers_of(engine, record)
  if (blockers.length > 0) {
    throw EngineError.validation(`no campaign report: ${blockers.join(', ')}`)
  }
  const resolved = engine.resolve_members(record)

  const run_dir = path.join(campaign.path, 'runs', String(run_id))
  const members_file: CampaignMembersFile = {
    run_id: run_id,
    campaign: record.campaign,
    params: record.params,
    members: resolved.map((member) => {
      const member_record = member.record as RunRecord
      const job_path = member.job_path as string
      return {
        run_id: member.run_id,
        job: member.job_name,
        params: all_params(member_record),
        submission_id: member_record.submission_id,
        report: primary_report_path(job_path, member.run_id),
        attachments:
          attachment_count(job_path, member.run_id) > 0
            ? attachment_dir(job_path, member.run_id)
            : null
      }
    })
  }
  write_atomic(path.join(run_dir, 'members.json'), JSON.stringify(members_file, null, 2))

  const folder = report_dir(campaign.path)
  try {
    fs.mkdirSync(folder, { recursive: true })
  } catch (cause) {
    throw EngineError.io(folder, cause)
  }
  prepare_attachments(campaign.path, run_id)
  const argv = [
    ...manifest.report.words,
    '--run',
    String(run_id),
    '--members',
    `runs/${run_id}/members.json`,
    '--attachment-dir',
    attachment_arg(run_id)
  ]
  let invocation: Invocation
  try {
    invocation = await invoke.run(campaign.path, argv, engine.config.report_timeout)
  } catch (cause) {
    throw EngineError.io(campaign.path, cause)
  } finally {
    settle_attachments(campaign.path, run_id)
  }

  const ok = invoke.invocation_ok(invocation) && report_on_disk(campaign.path, run_id)
  const error = ok
    ? undefined
    : invoke.invocation_ok(invocation)
      ? `report script exited 0 but produced neither report/${run_id}.txt nor report/${run_id}.html`
      : invoke.invocation_output(invocation)
  // The first outcome dates the campaign's end (§8.2); a regenerate's keeps it.
  record.report = {
    attempted: true,
    at: record.report?.at ?? now_stamp(),
    ...(error !== undefined ? { error } : {})
  }
  campaign.runs.write(record)

  if (!ok) {
    throw EngineError.invocation(
      manifest.report.display,
      invocation.exit,
      invocation.timed_out,
      error ?? ''
    )
  }
}
