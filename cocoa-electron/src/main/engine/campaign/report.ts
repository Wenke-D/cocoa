/** Why a campaign run has no report of its own: every member must have succeeded (§8.3). */
function blockers_of(engine: Engine, record: CampaignRecord): string[] {
  const reasons: string[] = []
  if (record.launch_failures.length > 0) {
    reasons.push(`${record.launch_failures.length} launch(es) failed`)
  }
  for (const member of engine.resolve_members(record)) {
    if (member.record === null) {
      reasons.push(`member \`${member.job_name}\` run ${member.run_id} cannot be resolved`)
    } else if (member.record.status !== 'SUCCEEDED') {
      reasons.push(
        `member \`${member.job_name}\` run ${member.run_id} ended ${member.record.status}`
      )
    }
  }
  return reasons
}

/**
 * Whether the campaign run's report can be regenerated by hand now: it has
 * had one — landed or failed — and is not already due again.
 */
export function campaign_report_rerunnable(engine: Engine, record: CampaignRecord): boolean {
  return record.report?.attempted === true && blockers_of(engine, record).length === 0
}

/**
 * Asks for a campaign run's report again, by hand (§8.3), as a job run's is
 * asked for (§7.3.2): nothing runs here. The report is marked due, the run
 * reads `ANALYZING`, and the refresh tick runs it. `at` is kept: it is the
 * campaign's end, which a regenerate does not move.
 */
export function request_campaign_report(engine: Engine, campaign: Campaign, run_id: number): void {
  campaign.usable_manifest()
  const record = campaign.runs.record(run_id)
  const blockers = blockers_of(engine, record)
  if (engine.awaiting_members.has(campaign.path, run_id)) {
    throw EngineError.validation(`the report of campaign run ${run_id} is already running`)
  }
  if (blockers.length > 0) {
    throw EngineError.validation(`no campaign report: ${blockers.join(', ')}`)
  }
  if (record.report === undefined || !record.report.attempted) {
    throw EngineError.validation(`the report of campaign run ${run_id} is already running`)
  }
  if (record.report_locked === true) {
    throw locked_refusal(`campaign run ${run_id}`, 'regenerate it')
  }
  mark_due(campaign, record)
}

/** Marks the campaign's own report due again, keeping `at`: the campaign's end. */
function mark_due(campaign: Campaign, record: CampaignRecord): void {
  const at = record.report?.at
  record.report = { attempted: false, ...(at !== undefined ? { at } : {}) }
  campaign.runs.write(record)
}

/**
 * Why a campaign run's members' reports cannot all be regenerated before its
 * own (§8.3), locks aside: every member must be finished on the path that
 * ends `SUCCEEDED` — succeeded, or left at `ERROR` by its own report — since
 * a `FAILED` or `CANCELLED` member leaves the campaign without a report.
 */
function member_blockers(engine: Engine, record: CampaignRecord): string[] {
  const reasons: string[] = []
  if (record.launch_failures.length > 0) {
    reasons.push(`${record.launch_failures.length} launch(es) failed`)
  }
  for (const member of engine.resolve_members(record)) {
    const name = `member \`${member.job_name}\` run ${member.run_id}`
    if (member.record === null) {
      reasons.push(`${name} cannot be resolved`)
    } else if (!is_terminal(member.record.status)) {
      reasons.push(`${name} (${member.record.status}) is not finished`)
    } else if (
      member.record.status !== 'SUCCEEDED' &&
      !(member.record.status === 'ERROR' && reportable(member.record, 'manual'))
    ) {
      reasons.push(`${name} ended ${member.record.status}`)
    }
  }
  return reasons
}

/** Whether the campaign run's own report is due, running, or waiting on its members'. */
function campaign_report_in_flight(engine: Engine, campaign: Campaign, run_id: number): boolean {
  return (
    engine.awaiting_members.has(campaign.path, run_id) ||
    campaign_status(engine, campaign, run_id).status === 'ANALYZING'
  )
}

/**
 * Whether every member's report, then the campaign's, can be regenerated by
 * hand now (§8.3), locks aside.
 */
export function members_report_rerunnable(
  engine: Engine,
  campaign: Campaign,
  record: CampaignRecord
): boolean {
  return (
    !campaign_report_in_flight(engine, campaign, record.run_id) &&
    member_blockers(engine, record).length === 0
  )
}

/**
 * While a campaign run waits on its members' regenerated reports (§8.3): how
 * many have landed, of how many. `null` when it is not waiting.
 */
export function members_progress(
  engine: Engine,
  campaign: Campaign,
  record: CampaignRecord
): { done: number; total: number } | null {
  if (!engine.awaiting_members.has(campaign.path, record.run_id)) {
    return null
  }
  const members = engine.resolve_members(record)
  return {
    done: members.filter((member) => member.record !== null && is_terminal(member.record.status))
      .length,
    total: members.length
  }
}

/**
 * Asks for every member's report again and then the campaign's (§8.3). All or
 * nothing: every refusal is found before any member is touched. Each member's
 * report is marked due under its own job, as `Regenerate` on its page would
 * (§7.3.2), and the campaign run waits in memory until they have landed;
 * `release_awaiting` takes it from there.
 */
export function request_members_report(engine: Engine, campaign: Campaign, run_id: number): void {
  campaign.usable_manifest()
  const record = campaign.runs.record(run_id)
  if (campaign_report_in_flight(engine, campaign, run_id)) {
    throw EngineError.validation(`the report of campaign run ${run_id} is already running`)
  }
  const blockers = member_blockers(engine, record)
  if (blockers.length > 0) {
    throw EngineError.validation(`cannot regenerate the members' reports: ${blockers.join(', ')}`)
  }
  if (record.report_locked === true) {
    throw locked_refusal(`campaign run ${run_id}`, 'regenerate it')
  }
  const members = engine.resolve_members(record)
  const locked = members.find((member) => member.record?.report_locked === true)
  if (locked !== undefined) {
    throw locked_refusal(`member \`${locked.job_name}\` run ${locked.run_id}`, 'regenerate it')
  }
  const jobs = members.map((member) => engine.job(member.job_path as string))
  for (const job of jobs) {
    job.usable_manifest()
  }
  members.forEach((member, index) => request_report(jobs[index], member.run_id))
  engine.awaiting_members.add(campaign.path, run_id)
}

/**
 * Moves on every campaign run waiting on its members' reports (§8.3), once
 * none is still reporting. All succeeded: the campaign's own report is marked
 * due, for this tick to run. Otherwise the wait ends there and the campaign's
 * report is left as it was; that stop is among the errors returned.
 */
export function release_awaiting(engine: Engine): EngineError[] {
  const errors: EngineError[] = []
  for (const [folder, run_id] of engine.awaiting_members.all()) {
    const campaign = engine.campaigns().find((candidate) => candidate.path === folder)
    const record = campaign?.runs.find(run_id) ?? null
    if (campaign === undefined || record === null) {
      engine.awaiting_members.delete(folder, run_id)
      continue
    }
    const members = engine.resolve_members(record)
    if (members.some((member) => member.record !== null && !is_terminal(member.record.status))) {
      continue
    }
    engine.awaiting_members.delete(folder, run_id)
    const stopped = members.find((member) => member.record?.status !== 'SUCCEEDED')
    if (stopped !== undefined) {
      errors.push(
        EngineError.validation(
          `the report of campaign run ${run_id} was not regenerated: member ` +
            `\`${stopped.job_name}\` run ${stopped.run_id} ` +
            (stopped.record === null ? 'cannot be resolved' : `ended ${stopped.record.status}`)
        )
      )
      continue
    }
    try {
      mark_due(campaign, record)
    } catch (cause) {
      errors.push(as_engine_error(folder, cause))
    }
  }
  return errors
}

/** Runs the campaign's report over its members' results (§8.3). */
export async function campaign_report(
  engine: Engine,
  campaign: Campaign,
  run_id: number
): Promise<void> {
  const manifest = campaign.usable_manifest()
  const record = campaign.runs.record(run_id)

  const blockers = blockers_of(engine, record)
  if (blockers.length > 0) {
    throw EngineError.validation(`no campaign report: ${blockers.join(', ')}`)
  }
  const resolved = engine.resolve_members(record)

  const run_dir = path.join(campaign.path, 'runs', String(run_id))
  const members_file: CampaignMembersFile = {
    run_id: run_id,
    campaign: record.campaign,
    params: record.params,
    members: resolved.map((member) => {
      const member_record = member.record as RunRecord
      const job_path = member.job_path as string
      return {
        run_id: member.run_id,
        job: member.job_name,
        params: all_params(member_record),
        submission_id: member_record.submission_id,
        report: primary_report_path(job_path, member.run_id),
        attachments:
          attachment_count(job_path, member.run_id) > 0
            ? attachment_dir(job_path, member.run_id)
            : null
      }
    })
  }
  write_atomic(path.join(run_dir, 'members.json'), JSON.stringify(members_file, null, 2))

  const folder = report_dir(campaign.path)
  try {
    fs.mkdirSync(folder, { recursive: true })
  } catch (cause) {
    throw EngineError.io(folder, cause)
  }
  prepare_attachments(campaign.path, run_id)
  const argv = [
    ...manifest.report.words,
    '--run',
    String(run_id),
    '--members',
    `runs/${run_id}/members.json`,
    '--attachment-dir',
    attachment_arg(run_id)
  ]
  let invocation: Invocation
  try {
    invocation = await invoke.run(campaign.path, argv, engine.config.report_timeout)
  } catch (cause) {
    throw EngineError.io(campaign.path, cause)
  } finally {
    settle_attachments(campaign.path, run_id)
  }

  const ok = invoke.invocation_ok(invocation) && report_on_disk(campaign.path, run_id)
  const error = ok
    ? undefined
    : invoke.invocation_ok(invocation)
      ? `report script exited 0 but produced neither report/${run_id}.txt nor report/${run_id}.html`
      : invoke.invocation_output(invocation)
  // The first outcome dates the campaign's end (§8.2); a regenerate's keeps it.
  record.report = {
    attempted: true,
    at: record.report?.at ?? now_stamp(),
    ...(error !== undefined ? { error } : {})
  }
  campaign.runs.write(record)

  if (!ok) {
    throw EngineError.invocation(
      manifest.report.display,
      invocation.exit,
      invocation.timed_out,
      error ?? ''
    )
  }
}
